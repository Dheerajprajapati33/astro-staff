/**
 * Helper to get today's remedy for a given rashi based on date
 * Calculates day of year % 15 to deterministically pick 1 of the 15 remedies for today
 */
export const getTodayUpayaForRashi = (
  rashiId = "mesh",
  targetDate = new Date(),
) => {
  const rashi = RASHIS.find((r) => r.id === rashiId) || RASHIS[0];
  const start = new Date(targetDate.getFullYear(), 0, 0);
  const diff = targetDate - start;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  const index = (dayOfYear + rashi.idIndex) % rashi.upayas.length;
  return {
    rashi,
    upaya: rashi.upayas[index],
    index: index + 1,
    total: rashi.upayas.length,
  };
};
