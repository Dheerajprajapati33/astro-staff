/**
 * Returns exact coordinates for a given place name (case-insensitive fuzzy match)
 */
export const getCoordinatesForPlace = (placeName) => {
  if (!placeName || typeof placeName !== "string") {
    return DEFAULT_COORDINATES;
  }

  const clean = placeName.trim().toLowerCase();

  // Exact or contains match
  const found = INDIAN_PLACES.find((p) => {
    const pName = p.name.toLowerCase();
    const pState = p.state.toLowerCase();
    return (
      clean === pName ||
      clean === pState ||
      clean.includes(pName) ||
      pName.includes(clean)
    );
  });

  if (found) {
    return {
      name: found.name,
      latitude: found.latitude,
      longitude: found.longitude,
      timezone: found.timezone,
    };
  }

  return DEFAULT_COORDINATES;
};
