// =====================================================
// CALCULATE LIFE PATH NUMBER
// =====================================================

export const calculateLifePathNumber = (dob) => {
  if (!dob) return null;

  const digits = String(dob).replace(/\D/g, "");

  if (!digits || digits.length < 6) {
    return null;
  }

  let sum = digits
    .split("")
    .reduce((total, digit) => total + Number(digit), 0);

  while (sum > 9) {
    sum = String(sum)
      .split("")
      .reduce((total, digit) => total + Number(digit), 0);
  }

  return sum;
};

// =====================================================
// CREATE A STABLE INDEX FROM NAME + DOB
// =====================================================

const createResponseIndex = (fullName, dob) => {
  const value = `${fullName || ""}-${dob || ""}`;

  let hash = 0;

  for (let i = 0; i < value.length; i++) {
    hash = (hash * 31 + value.charCodeAt(i)) >>> 0;
  }

  return hash % 15;
};

// =====================================================
// GET NUMEROLOGY RESULT
// =====================================================

export const getNumerologyResult = (fullName, dob) => {
  const number = calculateLifePathNumber(dob);

  if (!number || !NUMEROLOGY_RESPONSES[number]) {
    return null;
  }

  const index = createResponseIndex(fullName, dob);

  const response = NUMEROLOGY_RESPONSES[number][index];

  return {
    number,
    title: NUMEROLOGY_TITLES[number],
    description: response.description,
    aiInsight: response.aiInsight,
    responseIndex: index + 1,
  };
};